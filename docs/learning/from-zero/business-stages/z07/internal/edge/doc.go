// Package edge 实现 gateway-simulator 与 executor-simulator 的本地持久化运行时。
// GatewayCLI/ExecutorCLI 负责解析配置、绑定来源或执行器身份、建立 RPC 客户端并
// 管理数据库关闭；命令入口只创建受退出信号控制的 context。一个 bbolt 文件只由
// 一个进程持有，不是多个模拟器之间的共享消息队列。
//
// # 网关队列的确认边界
//
// Queue.Generate 在同一事务中分配实体版本与本地连续序号并保存事件；生成失败或
// 容量耗尽不得消耗分配器。Enqueue 可保存相同版本的刻意重复，不生成新的业务事件。
// 数据库保存 epoch、确认水位、版本分配器和未确认事件，重启不重新生成其身份与字节。
//
// Upload 每次只有一批连续消息在途，MarkSent 记录当前连接真正发送过的边界，ACK
// 必须属于相同 epoch 且不回退、不越过该边界。部分 ACK 只删除已确认前缀；未确认
// 后缀保持原样重放。重启或重连丢弃内存中的 sent 水位，而不丢弃持久化事件。
// drain=false 时空队列只意味着等待新生成事件；流的生命由 context 控制，单次
// Send/Recv 的超时不应成为整个长连接的固定寿命。关闭生成后仍需观察上传协程结果。
//
// # 执行收件箱与幂等墓碑
//
// Inbox 的 command、report、result 是权威本地事实，pending/active 桶只是派生
// 索引。OpenInbox 先完整验证旧文件，再原子重建索引；putEntry 在事实事务内维护
// 索引，因此取消、结果提交、报告确认和回滚不会留下提前释放的容量或丢失的待处理项。
// 完成记录仍是防止旧命令再次执行的墓碑；没有明确的安全重放边界，不能按年龄删除。
//
// RunExecutor 用独立接收循环和最多四个 worker，使取消可以在计时或结果提交前
// 持久化。非法命令会被计数并隔离，存储错误则终止运行，不能假装已经可靠接收。
// 取消与 CommitResult 在同一个 bbolt 写锁序列上竞争，先提交的模拟结果不会被
// 后到的取消抹除。未确定送达的 Report 保留相同 event_id 和完整请求；只有明确
// 回执、保证未接受的 ABORTED，或经权威查询证明可退役的拒绝，才解除待报告身份。
//
// 本包只模拟 inspect：四类执行器共用确定性的本地结果写入，六类状态来源共用
// 归一化链路。effect_count=1 证明的是一次本地结果事务，不是任意外部设备动作的
// 恰好一次保证。文件损坏时保留原文件诊断；离线队列压缩保留备份及完整序号/版本。
package edge
