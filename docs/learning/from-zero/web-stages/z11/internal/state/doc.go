// Package state 负责六类来源的归一化、状态接入、最新视图、订阅与有界历史采样。
// cmd/ingest 和 cmd/entity 由 internal/app 装配服务；Ingest 接收 Publisher，
// Entity 接收 Redis/MySQL 客户端。共享连接由装配层拥有，本包只管理自身消费、
// 采样、订阅与对账循环的 context、计时器和注册表。
//
// # 从来源到可查询状态
//
// adapters.go 将 person/drone/vehicle/robot/sensor/facility 的来源字段转换为
// 共享 EntityStateEvent，validation.go 核验身份、来源代次、版本、生命周期和
// 类型字段。可选组件缺失代表未知或不适用，不能补成零；执行能力由可信注册绑定
// 决定，遥测自报的 supported_tasks 不能授予权限。当前只有前四类可绑定 inspect。
//
// ReportEntityStates 验证整批后才开始对外发布。确认序号只前进到 Kafka 已确认
// 的连续前缀；后续单条发布成功也不能跨越前面的失败。调用方必须保留未确认后缀。
// 该确认只证明接入到 Kafka，不证明 Redis、MySQL 或浏览器已看见同一状态。
//
// 最新视图用 Redis Lua 原子比较来源代次与实体版本，拒绝旧值回退，区分相同事件
// 重复与同版本内容冲突。DELETE 保留版本墓碑，过期通过 expires_at 表达，不能
// 通过移除版本记录让旧事件重新成为最新状态。非法事件与版本冲突进入明确的
// 隔离诊断；Redis 故障返回错误让同一 Kafka 记录重试，不能当作成功提交消费进度。
//
// # 恢复、订阅与历史边界
//
// 最新投影的消费组与 Redis view generation 绑定，严格拒绝无证明的保留期缺口。
// 只有已经验证并激活的维护重建记录可以提供逐分区恢复水位；未完成的 building
// 标记或边界文件本身不构成豁免。运行时 generation 改变会停止旧投影，要求维护
// 后重新启动，不能拿旧消费进度继续填充一个已经丢失或替换的新命名空间。
//
// Subscribe 要求明确的 1..100 个实体 ID，先注册再读取初始化快照，之后发送
// SNAPSHOT_END 与去重更新。sync_id/view_generation 属于同步上下文，不是跨实体
// 通用游标。订阅缓冲受数量和字节限制；慢消费者被终止而非无限堆积。全局对账
// 合并活跃订阅需要的 Redis 版本查询；最后订阅退出会释放相应注册和循环。
//
// 历史采样使用独立消费组，受允许实体、年龄、周期及预算约束，允许按采样契约
// 舍弃候选，不能承诺完整原始历史。最新视图的恢复快照不恢复过去的历史样本，
// 因而不授予历史消费组相同恢复水位。MySQL 样本与去重记录在事务中一致维护；
// 清理有界分批执行。Entity.Run 任一组成循环退出后取消并等待其他循环，再把
// 错误交给装配层；网络或存储异常不能被包装成“零结果”或无损恢复。
